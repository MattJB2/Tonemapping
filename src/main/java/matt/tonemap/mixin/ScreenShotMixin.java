	private static void applyTonemap(File mcDir, int width, int height, CallbackInfoReturnable<String> cir) {
		//Can't use default shader in photomode, so we perform the tonemap in the screenshot method itself 
		System.out.println("[Tonemap] Screenshot inject is active.");
		for (int i = 0; i < imageData.length; i++) {
			int argb = imageData[i];
			int r = (argb >> 16) & 0xFF;
			int g = (argb >> 8) & 0xFF;
			int b = argb & 0xFF;

			// Normalize to [0,1] float
			float rf = r / 255f;
			float gf = g / 255f;
			float bf = b / 255f;

			// Find closest palette color
			float bestDistance = Float.MAX_VALUE;
			int bestMatch = 0;

			for (int p = 0; p < PALETTE.length; p++) {
				float pr = PALETTE[p][0];
				float pg = PALETTE[p][1];
				float pb = PALETTE[p][2];

				float dr = rf - pr;
				float dg = gf - pg;
				float db = bf - pb;

				float dist = dr * dr + dg * dg + db * db;
				if (dist < bestDistance) {
					bestDistance = dist;
					bestMatch = p;
				}
			}

			// Convert back to int RGB
			int pr = (int) (PALETTE[bestMatch][0] * 255);
			int pg = (int) (PALETTE[bestMatch][1] * 255);
			int pb = (int) (PALETTE[bestMatch][2] * 255);

			imageData[i] = (0xFF << 24) | (pr << 16) | (pg << 8) | pb;
		}
		System.out.println("[Tonemap] Screenshot inject is done.");
	}
